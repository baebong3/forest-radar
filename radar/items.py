def _compile(pats):
    return [re.compile(p) for p in pats]


for _it in ITEMS + [POLICY]:
    _it['_core'] = _compile(_it['core'])


def relevant(title, cfg):
    """품목 핵심어가 제목에 있을 때만 품목 기사로 인정 (밤 = night 같은 오탐 차단)"""
    t = title or ''
    return any(p.search(t) for p in cfg['_core'])


def classify(text):
    best, hit = '기타', 0
    for name, words in CATS:
        n = sum(1 for k in words if k in text)
        if n > hit:
            best, hit = name, n
    return best


def score(text):
    return sum(w for words, w in WEIGHTS if any(k in text for k in words))
